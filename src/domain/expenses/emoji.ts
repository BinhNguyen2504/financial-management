export type JarEmoji = string;

// Unicode's recommended emoji sequences include flags, keycaps, skin tones and
// ZWJ families. Also accept a single pictograph with an optional variation selector.
const singleEmoji = new RegExp(
  "^(?:\\p{RGI_Emoji}|\\p{Extended_Pictographic}\\uFE0F?)$",
  "v",
);
export function isJarEmoji(value: string): boolean {
  return (
    value.length <= 32 &&
    !/^\p{Emoji_Modifier}$/u.test(value) &&
    singleEmoji.test(value)
  );
}

export function jarEmoji(
  name: string,
  kind = "monthly",
  selected?: string | null,
): string {
  if (selected && isJarEmoji(selected)) return selected;
  const text = name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d");
  const matches: [RegExp, JarEmoji][] = [
    [/an uong|thuc pham|bua an|food/, "🍜"],
    [/nha|thue|home/, "🏡"],
    [/di chuyen|xe|xang|transport/, "🚲"],
    [/ca phe|cafe|coffee/, "☕"],
    [/mua sam|shopping/, "🛒"],
    [/dien|nuoc|internet|hoa don/, "💡"],
    [/hoc|sach|giao duc/, "📚"],
    [/suc khoe|y te|thuoc/, "💚"],
    [/du lich|nghi duong/, "✈️"],
    [/qua|sinh nhat/, "🎁"],
    [/thu cung|meo|cho /, "🐾"],
    [/so thich|giai tri/, "🎨"],
    [/tich luy|tiet kiem/, "🌱"],
  ];
  return (
    matches.find(([pattern]) => pattern.test(text))?.[1] ??
    (kind === "accumulation" ? "🌱" : "🫙")
  );
}
